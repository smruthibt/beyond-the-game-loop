#!/usr/bin/env python3
"""Primary-suite tables for REPORT.md.

    python3 benchmark/tools/report_tables.py --name NAME

Writes results/NAME/analysis/report_tables.md and report_tables.json, using
analyze.py's statistics (describe, paired) on runs.jsonl. Adds one derived
metric analyze.py cannot pair: the loop wall time of the endpoint that owns
the simulation, which is the server in client-server runs and the slowest peer
in peer-to-peer runs, so the topology comparison can be paired on it.
"""
import argparse
import json
from collections import defaultdict

from analyze import RESULTS, cond_label, describe, fmt, load, paired

COMPARISONS = ["information", "representation", "update", "topology"]
SWEEP_ORDER = [("moving", 10), ("moving", 100), ("moving", 500), ("static", 10), ("static", 100), ("static", 500),
               ("players", 2), ("players", 3), ("players", 4)]
METRICS = [   # (key, title, unit, value)
    ("e2e_s", "End-to-end completion time, 100,000 ticks", "s", lambda r: r["e2e_s"]),
    ("loop_wall_s", "Server loop wall time (client-server) / slowest peer loop wall time (P2P)", "s",
     lambda r: r.get("server_wall_s") if r.get("server_wall_s") is not None else r.get("peer_wall_max_s")),
    ("cpu_total_s", "CPU time, all processes (user + system)", "s", lambda r: r["cpu_total_s"]),
    ("rss_total_mb", "Peak memory, sum over processes", "MB", lambda r: r["rss_total_mb"]),
    ("received_mb", "Bytes received by all endpoints during measurement, data and control frames", "MB",
     lambda r: r["received_frame_bytes"] / 1e6),
]


def condition_text(sweep, level):
    return {"moving": f"{level} moving", "static": f"{level} static", "players": f"{level} players"}[sweep]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--name", required=True)
    a = ap.parse_args()
    cdir, manifest, rows, ledger = load(a.name)
    labels = {}
    for u in manifest["schedule"]["primary"]:
        labels[u["comparison"]] = {r["side"]: r["label"] for r in u["runs"]}
    sides = defaultdict(lambda: defaultdict(list))
    for r in rows:
        if r["suite"] == "primary":
            sides[(r["comparison"], r["sweep"], r["level"])][r["side"]].append(r)

    results = []
    md = [f"<!-- generated by tools/report_tables.py from results/{a.name}/runs.jsonl -->", "",
          "Each side: mean ± SD (sample variance in parentheses) over its 10 runs. Pairs share a seed and run "
          "back to back: B − A is the mean paired difference and B / A the geometric mean of the paired ratios, "
          "each with a 95% paired t interval (df = 9).", ""]
    for comp in COMPARISONS:
        la, lb = labels[comp]["A"], labels[comp]["B"]
        md.append(f"### {comp}: A = {la}, B = {lb}\n")
        for key, title, unit, value in METRICS:
            md += [f"**{title}** ({unit})", "",
                   f"| Condition | A: {la} | B: {lb} | B − A [95% CI] | B / A [95% CI] |", "|---|---:|---:|---:|---:|"]
            for sweep, level in SWEEP_ORDER:
                got = sides.get((comp, sweep, level))
                if not got:
                    md.append(f"| {condition_text(sweep, level)} | not run | | | |")
                    continue
                va = [(r["seed"], value(r)) for r in got["A"]]
                vb = [(r["seed"], value(r)) for r in got["B"]]
                sa, sb = describe([v for _, v in va]), describe([v for _, v in vb])
                p = paired(va, vb) or {}
                results.append({"comparison": comp, "A": la, "B": lb, "sweep": sweep, "level": level, "metric": key,
                                "unit": unit, "stats_A": sa, "stats_B": sb, "paired": p})

                def cell(s):
                    return f"{fmt(s['mean'])} ± {fmt(s['sd'])} ({fmt(s['var'])})" if s else "-"
                diff = f"{fmt(p['diff_mean'])} [{fmt(p['diff_lo'])}, {fmt(p['diff_hi'])}]" if p else "-"
                ratio = f"{p['ratio_gmean']:.3f} [{p['ratio_lo']:.3f}, {p['ratio_hi']:.3f}]" if p.get("ratio_gmean") else "-"
                md.append(f"| {condition_text(sweep, level)} | {cell(sa)} | {cell(sb)} | {diff} | {ratio} |")
            md.append("")
    adir = cdir / "analysis"
    (adir / "report_tables.md").write_text("\n".join(md))
    (adir / "report_tables.json").write_text(json.dumps(results, indent=1))
    print(f"{len(results)} rows -> {adir / 'report_tables.md'}")


if __name__ == "__main__":
    main()
